"""Generate the extended result tables of the supplementary file from committed outputs.

    .venv/bin/python scripts/m4_supplement_tables.py

Writes research/paper/supplementary_tables.md. No number in that file is typed by hand.
"""

from __future__ import annotations

import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "research" / "paper" / "supplementary_tables.md"


def rows(exp: str, name: str) -> list[dict]:
    with (ROOT / "research" / "experiments" / exp / "generated" / name).open() as f:
        return list(csv.DictReader(f))


def f4(x: str) -> str:
    return f"{float(x):+.4f}"


def ci(r: dict, lvl: str = "95") -> str:
    return f"[{float(r[f'ci{lvl}_low']):+.4f}, {float(r[f'ci{lvl}_high']):+.4f}]"


def p(r: dict, key: str) -> str:
    if not r.get(key):
        return "n/a"
    v = float(r[key])
    return "< 0.0001" if v < 0.0001 else f"{v:.4f}"


def main() -> int:
    out = ["<!-- SPDX-License-Identifier: LicenseRef-STREAK-NC-Research-1.0 -->",
           "# Supplementary tables (generated)",
           "",
           "Generated by `scripts/m4_supplement_tables.py` from the committed `generated/contrasts.csv` files "
           "of EXP-001 to EXP-003. Do not edit by hand. Intervals are 95% stratified percentile bootstrap "
           "intervals (10,000 resamples), unadjusted; p-values are bootstrap p-values, Holm-adjusted as the "
           "protocol specifies (within cell or variant for secondary contrasts; across the 27 cells for the "
           "EXP-002 primary contrast). A bootstrap p of 0 is shown as < 0.0001.",
           ""]
    for exp, title in (("EXP-001", "EXP-001, all contrasts (n = 1,000)"),
                       ("EXP-002", "EXP-002, all contrasts per cell (n = 500 per cell)"),
                       ("EXP-003", "EXP-003, all contrasts per model variant (n = 500 per variant)")):
        out += [f"## {title}", "",
                "| Cell | Kind | Contrast | n | Mean diff | SD | d_z | 95% CI | 90% CI | p | p (Holm) | Class |",
                "|---|---|---|---|---|---|---|---|---|---|---|---|"]
        for r in rows(exp, "contrasts.csv"):
            out.append(f"| {r['cell_id'].replace('|', ', ')} | {r['kind']} | {r['contrast']} | {r['n']} | {f4(r['mean_diff'])} | "
                       f"{float(r['sd_diff']):.4f} | {float(r['d_z']):.2f} | {ci(r)} | {ci(r, '90')} | "
                       f"{p(r, 'p_boot')} | {p(r, 'p_holm')} | {r['classification']} |")
        out.append("")
    OUT.write_text("\n".join(out) + "\n")
    print(f"wrote {OUT} ({len(out)} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
