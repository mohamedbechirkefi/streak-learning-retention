"""Fixture for the demo sandbox port (M5): Python engine outputs the browser port must match.

Writes ``demo/src/fixtures/engine_fixture.json`` with two parts.

1. ``exact``: small learner-arm cases. For each case the fixture stores the random
   draws the Python engine used (initial half-lives, availability, outcome uniforms)
   and the engine's outputs (final half-lives, last exposure, slots per day, residual,
   review trace and every per learner-arm metric). The TypeScript port is fed the
   same draws and must reproduce the trace exactly and the real-valued outputs within
   an absolute tolerance of 1e-9.
2. ``population``: mean R30 per arm and mean paired differences over 100 learners
   for two scenarios. The browser port draws its own random numbers, so these are
   compared within a stated Monte Carlo tolerance only.

Exploratory test data only: smoke seed 9001 (the smoke seed range), never a
confirmatory seed, no result file, no journal run. One process, a few seconds.

Usage: .venv/bin/python scripts/export_sandbox_fixture.py [--check]
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np

from streak import ENGINE_VERSION
from streak.metrics import learner_arm_metrics
from streak.params import ModelParams, get_arm
from streak.population import generate_learners
from streak.simulate import simulate_arm

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "demo/src/fixtures/engine_fixture.json"
SEED = 9001  # smoke seed range only

FROZEN = dict(n_items=200, horizon_days=56, budget_slots=672, slot_minutes=0.5, daily_cap_slots=60,
              fixed_weekdays=(1, 3, 5), h0=67.59, sigma_item=0.5, sigma_learner=0.3, g_min=0.1, a=2.5,
              b=0.6, h_min=0.25, q=0.85, form="exponential", gain_rule="difficulty")

EXACT_CASES = [
    ("small-default", {**FROZEN, "n_items": 30}, 2, ["A0", "A1", "A2", "A3", "D-RR", "F-EASY", "F-DUE"]),
    ("small-power-flat", {**FROZEN, "n_items": 30, "form": "power", "gain_rule": "flat", "q": 0.7, "h0": 33.8},
     2, ["A1", "A2", "A3"]),
    ("frozen-default", FROZEN, 1, ["A0", "A1", "A2", "A3"]),
]
POPULATION_CASES = [
    ("default", FROZEN, 100),
    ("floor", {**FROZEN, "h0": 1.0, "n_items": 100}, 100),
]


def params(d: dict) -> ModelParams:
    return ModelParams(**d)


def plain(d: dict) -> dict:
    return {k: (list(v) if isinstance(v, tuple) else v) for k, v in d.items()}


def exact_case(name: str, pdict: dict, n: int, arms: list[str]) -> dict:
    p = params(pdict)
    learners = []
    for lr in generate_learners(SEED, n, p):
        h_init = lr.initial_half_lives(p)
        av = lr.availability(p)
        runs = []
        for arm in arms:
            res = simulate_arm(h_init, av, lr.outcome_u, get_arm(arm), p)
            runs.append({
                "arm": arm,
                "half_life": res.half_life.tolist(),
                "last_review": res.last_review.tolist(),
                "daily_spent": res.daily_spent.tolist(),
                "residual": res.residual,
                "review_day": res.review_day.tolist(),
                "review_item": res.review_item.tolist(),
                "review_success": res.review_success.astype(int).tolist(),
                "metrics": learner_arm_metrics(res, p),
            })
        learners.append({"learner_index": lr.learner_index, "h_init": h_init.tolist(),
                         "available": av.astype(int).tolist(), "outcome_u": lr.outcome_u.tolist(),
                         "runs": runs})
    return {"name": name, "params": plain(pdict), "learners": learners}


def population_case(name: str, pdict: dict, n: int) -> dict:
    p = params(pdict)
    vals = {a: [] for a in ("A0", "A1", "A2", "A3")}
    act = {a: [] for a in vals}
    for lr in generate_learners(SEED, n, p):
        h_init, av = lr.initial_half_lives(p), lr.availability(p)
        for a in vals:
            m = learner_arm_metrics(simulate_arm(h_init, av, lr.outcome_u, get_arm(a), p), p)
            vals[a].append(m["R30"])
            act[a].append(m["active_days"])
    r = {a: np.asarray(v) for a, v in vals.items()}
    return {
        "name": name, "params": plain(pdict), "n_learners": n,
        "mean_R30": {a: float(v.mean()) for a, v in r.items()},
        "sd_R30": {a: float(v.std(ddof=1)) for a, v in r.items()},
        "mean_active_days": {a: float(np.mean(v)) for a, v in act.items()},
        "mean_diff": {"A2 - A1": float((r["A2"] - r["A1"]).mean()), "A3 - A1": float((r["A3"] - r["A1"]).mean())},
        "sd_diff": {"A2 - A1": float((r["A2"] - r["A1"]).std(ddof=1)), "A3 - A1": float((r["A3"] - r["A1"]).std(ddof=1))},
    }


def build() -> dict:
    return {
        "note": "Generated by scripts/export_sandbox_fixture.py from the Python engine (exploratory test data, smoke seed 9001). Not a research result.",
        "engine_version": ENGINE_VERSION,
        "seed": SEED,
        "tolerance_exact": 1e-9,
        "exact": [exact_case(*c) for c in EXACT_CASES],
        "population": [population_case(*c) for c in POPULATION_CASES],
    }


def serialise(d: dict) -> str:
    return json.dumps(d, separators=(",", ":")) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    text = serialise(build())
    if args.check:
        same = OUT.is_file() and OUT.read_text() == text
        print("engine_fixture.json up to date" if same else "engine_fixture.json differs from a fresh export")
        return 0 if same else 1
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)} ({len(text.encode())} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
